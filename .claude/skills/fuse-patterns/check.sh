#!/usr/bin/env bash
# mechanical checks for the bug classes that keep recurring in fuse.
# usage: check.sh [base-ref]   (default origin/main)
# prints FAIL / WARN / INFO lines; exits 1 if any FAIL.
# diff-scoped checks look at base...HEAD plus the working tree; repo-wide
# checks look at the tree as it is.

set -uo pipefail
cd "$(git rev-parse --show-toplevel)" || exit 2

BASE="${1:-origin/main}"
MB="$(git merge-base "$BASE" HEAD 2>/dev/null)" || { echo "cannot find merge-base with $BASE"; exit 2; }

fails=0
fail() { echo "FAIL  $*"; fails=$((fails + 1)); }
warn() { echo "WARN  $*"; }
info() { echo "INFO  $*"; }

# changed files: committed on the branch + staged + unstaged + untracked
CHANGED="$( { git diff --name-only "$MB"; git ls-files --others --exclude-standard; } | sort -u)"
changed() { grep -Eq "$1" <<<"$CHANGED"; }
added_lines() { git diff -U0 "$MB" -- "$@" | grep -E '^\+[^+]'; }

echo "base: $BASE ($MB)"
echo "changed files: $(grep -c . <<<"$CHANGED")"
echo

# --- 1. new orchestrator error sentinels must map to a status in api/errors.go
for name in $(added_lines 'internal/orchestrator/*.go' | grep -oE '\bErr[A-Z][A-Za-z0-9]* += *(errors\.New|fmt\.Errorf)' | grep -oE '^Err[A-Za-z0-9]+'); do
  grep -q "orchestrator\.$name\b" internal/api/errors.go \
    || fail "sentinel $name is new but not mapped in internal/api/errors.go classifyFleetError (it will 500)"
  grep -q "$name" internal/api/error_sentinels_test.go \
    || warn "sentinel $name has no case in internal/api/error_sentinels_test.go"
done

# --- 4. api types changed without openapi
if changed '^internal/api/(types|exec|computer|interventions)\.go$' && ! changed '^internal/api/openapi\.yaml$'; then
  fail "internal/api request/response structs changed but internal/api/openapi.yaml did not"
fi

# --- 3. sdk parity: touching one sdk's source means touching all four
langs_touched=()
langs_missing=()
for l in go typescript python rust; do
  if grep -E "^sdks/$l/" <<<"$CHANGED" | grep -Evq '(CHANGELOG|README|version\.ts|package-lock|Cargo\.lock|uv\.lock|go\.sum)'; then
    langs_touched+=("$l")
  else
    langs_missing+=("$l")
  fi
done
if [ ${#langs_touched[@]} -gt 0 ] && [ ${#langs_missing[@]} -gt 0 ]; then
  fail "sdk parity: touched ${langs_touched[*]}, untouched ${langs_missing[*]} (CLAUDE.md: all four move together)"
fi
for l in ${langs_touched[@]+"${langs_touched[@]}"}; do
  case $l in
    go) pat='^sdks/go/.*_test\.go$' ;;
    typescript) pat='^sdks/typescript/(test|tests|src)/.*\.test\.ts$' ;;
    python) pat='^sdks/python/tests/' ;;
    rust) pat='^sdks/rust/(tests/|src/.*\.rs$)' ;;
  esac
  changed "$pat" || warn "sdk $l changed with no test file changed"
done
if changed '^internal/api/(types|exec|computer|interventions)\.go$' && [ ${#langs_touched[@]} -eq 0 ]; then
  warn "api structs changed but no sdk changed: confirm the wire change needs no sdk update"
fi

# --- 13. ts version.ts drift
pkg_v="$(grep -m1 '"version"' sdks/typescript/package.json | grep -oE '[0-9]+\.[0-9]+\.[0-9]+')"
ts_v="$(grep -oE '[0-9]+\.[0-9]+\.[0-9]+' sdks/typescript/src/version.ts)"
[ "$pkg_v" = "$ts_v" ] || warn "sdks/typescript/src/version.ts says $ts_v, package.json says $pkg_v (regenerated by pretest, not committed)"

# --- 5. fc-agent change with no qemu-agent change: list shared functions
if changed '^host-agent/firecracker/fc-agent\.py$' && ! changed '^host-agent/qemu/qemu-agent\.py$'; then
  for fn in $(git diff "$MB" -- host-agent/firecracker/fc-agent.py | grep -oE '^@@.*def [a-z_0-9]+' | grep -oE '[a-z_0-9]+$' | sort -u); do
    grep -q "def $fn(" host-agent/qemu/qemu-agent.py \
      && warn "fc-agent.py:$fn changed; qemu-agent.py has $fn too and was not touched (one-sided fix?)"
  done
fi
added_lines host-agent | grep -E 'AF_UNIX|\.sock"' >/dev/null \
  && info "new unix socket path in host-agent: check it stays under 107 bytes for the longest vm id (SUN_LEN, #214)"

# --- 6. path containment in host agents
git diff -U0 "$MB" -- host-agent/firecracker/fc-agent.py host-agent/qemu/qemu-agent.py | grep -E '^\+[^+]' \
  | grep -E '(Path\(|os\.path\.join\().*\b(body|req|request|params|query|vm_id)\b' | grep -v vm_dir \
  | while read -r l; do warn "host-agent path built from request data outside vm_dir(): ${l:1:140}"; done

# --- 14. every host-agent unittest file runs in ci
for f in host-agent/*/tests/test_*.py; do
  mod="$(basename "$f" .py)"
  grep -q "$mod" .github/workflows/ci.yml || warn "$f is not run by .github/workflows/ci.yml"
done

# --- 7. copied shell helpers must stay identical
helper_hashes() {
  local fn="$1"; shift
  for f in "$@"; do [ -f "$f" ] || continue; awk "/^$fn\\(\\)/,/^}/" "$f" | shasum; done | sort -u | grep -c .
}
sha_files=(host-agent/local/fuse-local-setup.sh host-agent/firecracker/scripts/fc-agent.sh host-agent/firecracker/scripts/fc-update.sh ops/install-fuse.sh ops/install-proxy.sh ops/install-orchestrator.sh)
[ "$(helper_hashes sha256_of "${sha_files[@]}")" = 1 ] || fail "sha256_of() differs between ${sha_files[*]}"
rule_files=(host-agent/firecracker/scripts/fc-warp.sh host-agent/firecracker/scripts/fc-wireguard.sh)
[ "$(helper_hashes rule "${rule_files[@]}")" = 1 ] || fail "rule() differs between ${rule_files[*]}"
added_lines '*.sh' '*.py' | grep -E 'iptables +(-I|-A|-D|-C) +[^ ]+ +-t ' \
  | while read -r l; do fail "iptables table flag must come first (-t nat -I ...): ${l:1:140}"; done

# --- 8. http calls without timeouts
added_lines '*.go' | grep -E 'http\.Client\{ *\}|http\.(Get|Post)\(' \
  | while read -r l; do warn "go http call with no timeout: ${l:1:140}"; done
added_lines '*.py' | grep -E '(urlopen|requests\.(get|post|put|delete))\(' | grep -v timeout \
  | while read -r l; do warn "python http call with no timeout: ${l:1:140}"; done

# --- 2. e2e exec output compared without decoding
added_lines 'test/e2e' | grep -E '\.(stdout|stderr)\b' | grep -Ev 'base64|b64' \
  | while read -r l; do warn "e2e reads exec stdout/stderr without base64 decode (vacuous-assert risk, #220): ${l:1:140}"; done

# --- 10. fusefile fields must reach the cli create request
if changed '^internal/fusefile/(compile|parse)\.go$'; then
  changed '^cli/(up|build)_cmd\.go$' || warn "internal/fusefile changed but cli/up_cmd.go / cli/build_cmd.go did not: is the new field copied into the create request? (#325)"
  changed '^schema/fusefile-v1\.json$' || warn "internal/fusefile changed but schema/fusefile-v1.json did not"
fi

# --- systemd unit placement
grep -E '\.service$' <<<"$CHANGED" | grep -v '^ops/systemd/' | grep -v '^host-agent/firecracker/fused\.service$' \
  | while read -r f; do warn "$f: new/changed .service outside ops/systemd/ (CLAUDE.md)"; done

# --- docs touched when behavior changed
code_changed=$(grep -cE '^(internal|cli|fused|orchestrator|proxy|host-agent|sdks|schema)/' <<<"$CHANGED")
if [ "$code_changed" -gt 0 ] && ! changed '^docs/content/'; then
  info "code changed but docs/content/ did not: run the docs-sync skill to confirm nothing user-visible moved"
fi

echo
[ "$fails" -eq 0 ] && echo "no FAIL findings" || echo "$fails FAIL finding(s)"
[ "$fails" -eq 0 ]
